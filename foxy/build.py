"""
Foxy Pipeline - Step 3: Build
Scaffolds starter files and performs branding/config token replacement for matched leads.
Generates a structured skeleton folder for custom leads.
"""

import os
import json
from typing import Dict, Any

def execute_build(lead_id: str, client_ref: str, spec: Dict[str, Any], match_result: Dict[str, Any], templates_path: str = "templates.json") -> Dict[str, Any]:
    """Execute the build step into builds/<lead-id>/."""
    build_dir = os.path.join("builds", lead_id)
    os.makedirs(build_dir, exist_ok=True)

    status = match_result.get("status")
    template_id = match_result.get("template_id")

    if status == "matched" and template_id:
        return build_matched_template(build_dir, lead_id, client_ref, spec, template_id, templates_path)
    else:
        return build_custom_skeleton(build_dir, lead_id, client_ref, spec)

def build_matched_template(build_dir: str, lead_id: str, client_ref: str, spec: Dict[str, Any], template_id: str, templates_path: str) -> Dict[str, Any]:
    """Scaffold matched template files and replace template variables."""
    templates = []
    if os.path.exists(templates_path):
        with open(templates_path, "r", encoding="utf-8") as f:
            templates = json.load(f)

    target_template = next((t for t in templates if t["id"] == template_id), None)
    if not target_template:
        return build_custom_skeleton(build_dir, lead_id, client_ref, spec)

    starter_files = target_template.get("starter_files", {})
    files_written = []

    # Token map for substitutions
    client_name = client_ref.split("(")[0].strip() if "(" in client_ref else client_ref.strip()
    tagline = f"Automated solution for {client_name}"
    bot_role = f"Specialized assistant for {client_name}"

    token_map = {
        "{{CLIENT_NAME}}": client_name,
        "{{LEAD_ID}}": lead_id,
        "{{BOT_ROLE}}": bot_role,
        "{{CLIENT_TAGLINE}}": tagline,
        "{{TEMPLATE_ID}}": template_id
    }

    for filename, raw_content in starter_files.items():
        processed_content = raw_content
        for token, val in token_map.items():
            processed_content = processed_content.replace(token, val)

        filepath = os.path.join(build_dir, filename)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(processed_content)
        files_written.append(filename)

    # Add Foxy build manifest
    manifest = {
        "lead_id": lead_id,
        "client": client_name,
        "template_id": template_id,
        "build_mode": "matched_template",
        "features": spec.get("features", []),
        "files": files_written,
        "instructions": "Starter codebase scaffolded and brand tokens swapped. Teja approval required before manual delivery."
    }
    with open(os.path.join(build_dir, "foxy_manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
    files_written.append("foxy_manifest.json")

    return {
        "mode": "matched_template",
        "template_id": template_id,
        "files_created": len(files_written),
        "file_list": files_written,
        "build_path": f"builds/{lead_id}/"
    }

def build_custom_skeleton(build_dir: str, lead_id: str, client_ref: str, spec: Dict[str, Any]) -> Dict[str, Any]:
    """Generate architectural skeleton for bespoke projects."""
    files_written = []

    # 1. Custom README
    readme_content = f"""# {client_ref} — Custom Build Architecture
Status: NEEDS CUSTOM BUILD
Lead ID: {lead_id}

## Spec Overview
- Type: {spec.get('type', 'app')}
- Target Platforms: {', '.join(spec.get('platform', ['web']))}
- Requested Features:
{chr(10).join(f'  - {feat}' for feat in spec.get('features', []))}

## Constraints
{chr(10).join(f'  - {c}' for c in spec.get('constraints', []))}

## Implementation Plan
1. Core business logic architecture
2. Integration with client environment
3. QA & Security testing
4. Manual submission by Teja

Generated by Foxy (Vyshu Sub-Agent).
"""
    with open(os.path.join(build_dir, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme_content)
    files_written.append("README.md")

    # 2. Skeleton Config
    spec_export = {
        "lead_id": lead_id,
        "client_ref": client_ref,
        "mode": "custom_skeleton",
        "spec": spec,
        "next_action": "Teja manual review and architecture approval required"
    }
    with open(os.path.join(build_dir, "custom_spec.json"), "w", encoding="utf-8") as f:
        json.dump(spec_export, f, indent=2)
    files_written.append("custom_spec.json")

    # 3. Modular starter source placeholder
    os.makedirs(os.path.join(build_dir, "src"), exist_ok=True)
    with open(os.path.join(build_dir, "src", "index.py"), "w", encoding="utf-8") as f:
        f.write(f'"""\nCustom logic entry point for {client_ref}\nLead ID: {lead_id}\n"""\n\ndef main():\n    print("Starting custom build execution for {client_ref}")\n\nif __name__ == "__main__":\n    main()\n')
    files_written.append("src/index.py")

    return {
        "mode": "skeleton_only",
        "template_id": None,
        "files_created": len(files_written),
        "file_list": files_written,
        "build_path": f"builds/{lead_id}/"
    }

