import React, { useState, useEffect } from 'react';
import { 
  Folder, 
  FileText, 
  FileCode, 
  Copy, 
  Check, 
  ExternalLink,
  Download,
  Terminal,
  RefreshCw
} from 'lucide-react';

interface BuildsExplorerProps {
  initialLeadId?: string | null;
  buildDirs: string[];
}

export const BuildsExplorer: React.FC<BuildsExplorerProps> = ({
  initialLeadId,
  buildDirs,
}) => {
  const [selectedDir, setSelectedDir] = useState<string>(
    initialLeadId && buildDirs.includes(initialLeadId)
      ? initialLeadId
      : buildDirs.length > 0
      ? buildDirs[0]
      : ''
  );
  const [filesData, setFilesData] = useState<Record<string, string>>({});
  const [selectedFile, setSelectedFile] = useState<string>('');
  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [copied, setCopied] = useState<boolean>(false);

  useEffect(() => {
    if (initialLeadId && buildDirs.includes(initialLeadId)) {
      setSelectedDir(initialLeadId);
    }
  }, [initialLeadId, buildDirs]);

  const loadBuildFiles = async (dirName: string) => {
    if (!dirName) return;
    setIsLoading(true);
    try {
      const res = await fetch(`/api/builds/${dirName}`);
      if (res.ok) {
        const data = await res.json();
        setFilesData(data.files || {});
        const fileNames = Object.keys(data.files || {});
        if (fileNames.length > 0) {
          // Default to README.md or first file
          const defaultFile = fileNames.find((f) => f.toLowerCase().includes('readme')) || fileNames[0];
          setSelectedFile(defaultFile);
        } else {
          setSelectedFile('');
        }
      }
    } catch (err) {
      console.error('Failed to load build files:', err);
    } finally {
      setIsLoading(false);
    }
  };

  useEffect(() => {
    if (selectedDir) {
      loadBuildFiles(selectedDir);
    }
  }, [selectedDir]);

  const handleCopy = () => {
    if (!selectedFile || !filesData[selectedFile]) return;
    navigator.clipboard.writeText(filesData[selectedFile]);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const fileList = Object.keys(filesData);

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 py-6 space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-5 rounded-xl bg-slate-900/60 border border-slate-800">
        <div>
          <h1 className="text-xl font-bold text-white tracking-tight flex items-center gap-2">
            <span>Builds Repository Explorer</span>
            <span className="text-xs px-2 py-0.5 rounded bg-orange-500/15 text-orange-300 font-mono">
              builds/{selectedDir || '...'}/
            </span>
          </h1>
          <p className="text-sm text-slate-400 mt-1">
            Isolated code artifacts generated by Foxy for each freelance client inquiry.
          </p>
        </div>

        {/* Directory Picker */}
        <div className="flex items-center gap-3">
          <label className="text-xs text-slate-400 font-medium">Select Lead Build:</label>
          <select
            value={selectedDir}
            onChange={(e) => setSelectedDir(e.target.value)}
            className="px-3 py-2 text-xs font-mono bg-slate-950 border border-slate-800 rounded-lg text-slate-200 focus:outline-none focus:border-orange-500"
          >
            {buildDirs.map((dir) => (
              <option key={dir} value={dir}>
                {dir}
              </option>
            ))}
          </select>
          <button
            onClick={() => loadBuildFiles(selectedDir)}
            className="p-2 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 transition-colors"
            title="Reload files"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isLoading ? 'animate-spin' : ''}`} />
          </button>
        </div>
      </div>

      {buildDirs.length === 0 ? (
        <div className="p-12 text-center rounded-xl bg-slate-900/40 border border-slate-800 text-slate-400">
          No builds found in the builds/ folder. Run a pipeline from the runner to generate your first starter code.
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
          {/* File Tree (4 cols) */}
          <div className="lg:col-span-4 p-4 rounded-xl bg-slate-900/70 border border-slate-800 space-y-3">
            <div className="flex items-center justify-between pb-2 border-b border-slate-800">
              <span className="text-xs font-semibold text-slate-400 uppercase tracking-wider flex items-center gap-2">
                <Folder className="w-3.5 h-3.5 text-orange-400" />
                Files ({fileList.length})
              </span>
              <span className="text-[11px] font-mono text-slate-500">
                builds/{selectedDir}/
              </span>
            </div>

            <div className="space-y-1">
              {fileList.map((filename) => {
                const isSelected = selectedFile === filename;
                const isCode = filename.endsWith('.js') || filename.endsWith('.ts') || filename.endsWith('.py');
                const isJson = filename.endsWith('.json');

                return (
                  <button
                    key={filename}
                    onClick={() => setSelectedFile(filename)}
                    className={`w-full text-left px-3 py-2 rounded-lg text-xs font-mono flex items-center justify-between transition-colors ${
                      isSelected
                        ? 'bg-orange-500/15 text-orange-300 border border-orange-500/30'
                        : 'text-slate-300 hover:bg-slate-800/60'
                    }`}
                  >
                    <div className="flex items-center gap-2 truncate">
                      {isCode ? (
                        <FileCode className="w-3.5 h-3.5 text-orange-400 shrink-0" />
                      ) : (
                        <FileText className="w-3.5 h-3.5 text-slate-400 shrink-0" />
                      )}
                      <span className="truncate">{filename}</span>
                    </div>
                  </button>
                );
              })}
            </div>

            {/* Quick Terminal Tip */}
            <div className="pt-3 border-t border-slate-800/80 text-[11px] text-slate-500 space-y-1">
              <div className="font-semibold text-slate-400 flex items-center gap-1.5">
                <Terminal className="w-3 h-3 text-orange-400" />
                <span>Termux / CLI Command</span>
              </div>
              <code className="block bg-slate-950 p-2 rounded text-slate-400 font-mono select-all">
                cd builds/{selectedDir}
              </code>
            </div>
          </div>

          {/* File Content Viewer (8 cols) */}
          <div className="lg:col-span-8 p-5 rounded-xl bg-slate-900/70 border border-slate-800 space-y-4">
            <div className="flex items-center justify-between pb-3 border-b border-slate-800">
              <div className="flex items-center gap-2">
                <FileCode className="w-4 h-4 text-orange-400" />
                <span className="text-xs font-mono font-semibold text-white">
                  {selectedFile || 'No file selected'}
                </span>
              </div>

              <div className="flex items-center gap-2">
                <button
                  onClick={handleCopy}
                  className="px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs flex items-center gap-1.5 transition-colors"
                >
                  {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                  <span>{copied ? 'Copied' : 'Copy File'}</span>
                </button>
              </div>
            </div>

            {isLoading ? (
              <div className="p-12 text-center text-xs text-slate-500 font-mono">
                Loading build files...
              </div>
            ) : selectedFile ? (
              <div className="relative">
                <pre className="p-4 bg-slate-950 rounded-lg border border-slate-800/80 font-mono text-xs text-slate-200 leading-relaxed overflow-x-auto max-h-[500px]">
                  {filesData[selectedFile]}
                </pre>
              </div>
            ) : (
              <div className="p-12 text-center text-xs text-slate-500 font-mono">
                Select a file from the left to view contents.
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
};
